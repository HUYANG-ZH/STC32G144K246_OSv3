uint8 roundabout_priority_tree_predict(float y1, float x1, float x2, float y2, float m)
{
    int16 node = 0;

    while (kFeature[node] >= 0)
    {
        float value;

        switch (kFeature[node])
        {
            case 0: value = y1; break;
            case 1: value = x1; break;
            case 2: value = x2; break;
            case 3: value = y2; break;
            default: value = m; break;
        }

        node = (value <= kThreshold[node]) ? kLeft[node] : kRight[node];
    }

    return (0U != kResult[node]) ? 1U : 0U;
}
