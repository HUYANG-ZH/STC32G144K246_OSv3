#include "shared_lpf.h"

static float shared_lpf_clamp_alpha(float alpha);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化一阶低通滤波器
// 参数说明     filter          滤波器对象指针
// 参数说明     alpha           滤波系数 [0.0f, 1.0f]
// 参数说明     init_value      初始输出值
// 返回参数     void
// 使用示例     shared_lpf_init(&filter, 0.2f, 0.0f);
//-------------------------------------------------------------------------------------------------------------------
void shared_lpf_init(shared_lpf_t *filter, float alpha, float init_value)
{
    filter->alpha = shared_lpf_clamp_alpha(alpha);
    filter->output = init_value;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置一阶低通滤波器系数
// 参数说明     filter          滤波器对象指针
// 参数说明     alpha           滤波系数 [0.0f, 1.0f]
// 返回参数     void
// 使用示例     shared_lpf_set_alpha(&filter, 0.5f);
//-------------------------------------------------------------------------------------------------------------------
void shared_lpf_set_alpha(shared_lpf_t *filter, float alpha)
{
    filter->alpha = shared_lpf_clamp_alpha(alpha);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     重置一阶低通滤波器输出值
// 参数说明     filter          滤波器对象指针
// 参数说明     value           重置后的输出值
// 返回参数     void
// 使用示例     shared_lpf_reset(&filter, 0.0f);
//-------------------------------------------------------------------------------------------------------------------
void shared_lpf_reset(shared_lpf_t *filter, float value)
{
    filter->output = value;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新一阶低通滤波器
// 参数说明     filter          滤波器对象指针
// 参数说明     input           本次输入值
// 返回参数     float           本次滤波输出值
// 使用示例     value = shared_lpf_update(&filter, input);
//-------------------------------------------------------------------------------------------------------------------
float shared_lpf_update(shared_lpf_t *filter, float input)
{
    filter->output = filter->output + filter->alpha * (input - filter->output);

    return filter->output;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取一阶低通滤波器当前输出值
// 参数说明     filter          滤波器对象指针
// 返回参数     float           当前输出值
// 使用示例     value = shared_lpf_get(&filter);
//-------------------------------------------------------------------------------------------------------------------
float shared_lpf_get(const shared_lpf_t *filter)
{
    return filter->output;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     限制一阶低通滤波器系数范围
// 参数说明     alpha           待限制的滤波系数
// 返回参数     float           限制后的滤波系数
//-------------------------------------------------------------------------------------------------------------------
static float shared_lpf_clamp_alpha(float alpha)
{
    if(alpha < 0.0f)
    {
        alpha = 0.0f;
    }
    else if(1.0f < alpha)
    {
        alpha = 1.0f;
    }

    return alpha;
}
